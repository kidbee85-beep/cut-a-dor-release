#!/usr/bin/env python3
"""Rebuild Cut-A-Dor's seekable IMA library from the bundled CC0 PCM sources."""
import array, json, math, struct, wave
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
STEP=[7,8,9,10,11,12,13,14,16,17,19,21,23,25,28,31,34,37,41,45,50,55,60,66,73,80,88,97,107,118,130,143,157,173,190,209,230,253,279,307,337,371,408,449,494,544,598,658,724,796,876,963,1060,1166,1282,1411,1552,1707,1878,2066,2272,2499,2749,3024,3327,3660,4026,4428,4871,5358,5894,6484,7132,7845,8630,9493,10442,11487,12635,13899,15289,16818,18500,20350,22385,24623,27086,29794,32767]
DELTA=[-1,-1,-1,-1,2,4,6,8]
def encode(pcm):
 out=bytearray();idx=0
 for start in range(0,len(pcm),256):
  pred=int(pcm[start]);out+=struct.pack('<hBB',pred,idx,0);codes=[]
  for x in list(pcm[start:start+256])+[0]*max(0,start+256-len(pcm)):
   d=int(x)-pred;n=8 if d<0 else 0;d=abs(d);s=STEP[idx];diff=s>>3
   for bit,val in [(4,s),(2,s>>1),(1,s>>2)]:
    if d>=val:n|=bit;d-=val;diff+=val
   pred=max(-32768,min(32767,pred+(-diff if n&8 else diff)));idx=max(0,min(88,idx+DELTA[n&7]));codes.append(n)
  out+=bytes(codes[i]|codes[i+1]<<4 for i in range(0,256,2))
 return bytes(out)
def read(p):
 with wave.open(str(p)) as w:
  assert w.getnchannels()==1 and w.getsampwidth()==2
  return w.getframerate(),array.array('h',w.readframes(w.getnframes()))
def wav(p,rate,pcm):
 with wave.open(str(p),'wb') as w:w.setnchannels(1);w.setsampwidth(2);w.setframerate(rate);w.writeframes(array.array('h',pcm).tobytes())
def main():
 spec=json.loads((ROOT/'sound-src/manifest.json').read_text());samples=[];pcms=[]
 for s in spec:
  rate,pcm=read(ROOT/'sound-src'/s['file']);samples.append(dict(s,rate=rate,frames=len(pcm)));pcms.append(pcm)
 # Windowed-sinc antialiasing for 22.05k recorded hats/snare in 16k breaks.
 cache={}
 def for_break(sid):
  if sid in cache:return cache[sid]
  rate=samples[sid]['rate'];p=pcms[sid]
  if rate==16000:cache[sid]=p;return p
  ratio=16000/rate;cut=.46*min(1,ratio);out=[]
  for j in range(round(len(p)*ratio)):
   at=j/ratio;centre=int(at);total=weight=0.0
   for k in range(centre-12,centre+13):
    d=k-at
    if abs(d)>12:continue
    sinc=2*cut if abs(d)<1e-9 else math.sin(2*math.pi*cut*d)/(math.pi*d)
    w=sinc*(.5+.5*math.cos(math.pi*d/12));weight+=w
    total+=p[min(max(k,0),len(p)-1)]*w
   out.append(round(total/weight))
  cache[sid]=out;return out
 # These are original, exactly one-bar arrangements of CC0 hits, not recordings of records.
 names=['DOJO DUST','NIGHT BUS','CONCRETE CUT','SOUL POCKET','ROOFTOP FUNK','BROKEN HALO','SUBWAY SWING','SIDE A','SIDE B','IRON BOOM','FAST HANDS','LAST TRAIN']
 bpms=[82,88,96,76,108,92,86,90,100,80,120,110]
 for k,(name,bpm) in enumerate(zip(names,bpms)):
  rate=16000;n=round(rate*240/bpm);mix=[0.0]*n
  # Curated acoustic voices, paired consistently with the firmware kits.
  kit=[[4,18,31,29,41,56,42,47],[5,19,33,38,40,57,43,48],
       [6,20,34,29,45,58,44,49],[7,21,35,38,41,59,42,47],
       [8,22,31,29,40,60,43,48],[9,23,33,38,46,55,44,49]][k%6]
  def hit(sid,st,vel=1):
   p=for_break(sid);offset=round((st+(0.10 if int(st)%2 else 0))*n/16)
   for j,v in enumerate(p):mix[(offset+j)%n]+=v*vel
  kicks=[[0,6,10],[0,7,10.5],[0,3,8,10],[0,6.5,11],[0,2,6,9,14],[0,5,10,15]][k%6]
  for st in kicks:hit(kit[0],st,.82)
  for st in [4,12]:hit(kit[1],st,.76)
  for st in range(0,16,1 if k%3==2 else 2):hit(kit[2],st,.17 if st%2 else .30)
  for st in [3.5,11,15]:hit(kit[1],st,.16)
  for st in [6,14]:hit(kit[5],st,.22)
  peak=max(abs(x) for x in mix);gain=26000/max(26000,peak)
  pcm=[round(x*gain) for x in mix]
  for j in range(32):pcm[j]=round(pcm[j]*j/32);pcm[-1-j]=round(pcm[-1-j]*j/32)
  fn=f'break_{k+1:02}.wav';wav(ROOT/'sound-src'/fn,rate,pcm)
  samples.append(dict(id=f'cad_break_{k+1:02}',name=name,category=8,file=fn,rate=rate,frames=n,bpm=bpm,license='CC0-1.0',origin='Original Cut-A-Dor arrangement of bundled CC0 hits'));pcms.append(pcm)
 out=ROOT/'build/gen';out.mkdir(parents=True,exist_ok=True);dist=ROOT/'dist/sounds';dist.mkdir(parents=True,exist_ok=True)
 chunks=[];meta=[];blob=bytearray()
 for old in dist.glob('*.ima'):old.unlink()
 for i,(s,p) in enumerate(zip(samples,pcms)):
  data=encode(p);off=len(blob);blob+=data
  chunks.append(f'static const uint8_t sample_{i}[]={{\n'+',\n'.join(','.join(map(str,data[j:j+32])) for j in range(0,len(data),32))+'\n};')
  meta.append(dict(s,index=i,offset=off,bytes=len(data)))
  (dist/(s['id']+'.ima')).write_bytes(data)
 h='/* Generated by tools/make_samples.py; CC0 sample data. */\n#define CAD_FACTORY_COUNT '+str(len(meta))+'\n'+'\n'.join(chunks)+'\nstatic const cad_sample cad_factory[]={\n'
 h+='\n'.join(f'{{sample_{i},{s["frames"]},{s["rate"]},{s["category"]},{json.dumps(s["name"][:15])}}},' for i,s in enumerate(meta))+'\n};\n'
 (out/'cad_samples.h').write_text(h);(ROOT/'dist/library.json').write_text(json.dumps(meta,indent=2));(out/'library.json').write_text(json.dumps(meta,indent=2))
 print(f'{len(meta)} sounds, {len(blob)} compressed bytes, {sum(s["frames"] for s in meta)} samples')
if __name__=='__main__':main()
